static void method_uart_write(const fx_req* req, fx_str params, bool have_params) {
  char name[FX_NAME_MAX];
  char hex[FX_PAYLOAD_MAX * 2 + 1];
  if (!want_str(req, params, have_params, "channel", name, sizeof(name))) return;
  int idx = find_uart(name);
  if (idx < 0) {
    reply_error(req, -32001, "no such uart channel", name);
    return;
  }
  if (!want_str(req, params, have_params, "hex", hex, sizeof(hex))) return;
  uint8_t payload[FX_PAYLOAD_MAX];
  long n = hex_decode(hex, payload, sizeof(payload));
  if (n < 0) {
    reply_error(req, -32602, "invalid params", "hex must be an even number of hex digits");
    return;
  }
  if (!guard_satisfied(fx_uart[idx].guard)) {
    reply_error(req, -32003, "guard not asserted", guard_name(fx_uart[idx].guard));
    return;
  }
  size_t written = fx_hal_uart_write(fx_uart[idx].index, payload, (size_t)n);
  fx_out o;
  out_head(&o, req);
  out_lit(&o, ",\"result\":{");
  out_kv_long(&o, "written", (long)written);
  out_lit(&o, "}}");
  out_flush(&o);
}

static void method_uart_read(const fx_req* req, fx_str params, bool have_params) {
  char name[FX_NAME_MAX];
  if (!want_str(req, params, have_params, "channel", name, sizeof(name))) return;
  int idx = find_uart(name);
  if (idx < 0) {
    reply_error(req, -32001, "no such uart channel", name);
    return;
  }
  long max = FX_PAYLOAD_MAX;
  fx_str v;
  if (have_params && obj_get(params.p, params.p + params.n, "max", &v)) {
    if (!int_value(v, &max) || max < 0) {
      reply_error(req, -32602, "invalid params", "max");
      return;
    }
  }
  if (max > FX_PAYLOAD_MAX) max = FX_PAYLOAD_MAX;
  uint8_t payload[FX_PAYLOAD_MAX];
  size_t n = fx_hal_uart_read(fx_uart[idx].index, payload, (size_t)max);
  fx_out o;
  out_head(&o, req);
  out_lit(&o, ",\"result\":{");
  out_key(&o, "hex");
  out_hex(&o, payload, n);
  out_char(&o, ',');
  out_kv_long(&o, "length", (long)n);
  out_lit(&o, "}}");
  out_flush(&o);
}

static void method_uart_configure(const fx_req* req, fx_str params, bool have_params) {
  char name[FX_NAME_MAX];
  long baud = 0;
  if (!want_str(req, params, have_params, "channel", name, sizeof(name))) return;
  int idx = find_uart(name);
  if (idx < 0) {
    reply_error(req, -32001, "no such uart channel", name);
    return;
  }
  if (!want_long(req, params, have_params, "baud", &baud)) return;
  if (baud <= 0) {
    reply_error(req, -32602, "invalid params", "baud must be positive");
    return;
  }
  const fx_uart_desc* u = &fx_uart[idx];
  fx_hal_uart_configure(u->index, (uint32_t)baud, u->data_bits, u->stop_bits, u->parity);
  reply_ok_empty(req);
}

static void method_i2c_scan(const fx_req* req, fx_str params, bool have_params) {
  char name[FX_NAME_MAX];
  if (!want_str(req, params, have_params, "channel", name, sizeof(name))) return;
  int idx = find_i2c(name);
  if (idx < 0) {
    reply_error(req, -32001, "no such i2c channel", name);
    return;
  }
  if (!guard_satisfied(fx_i2c[idx].guard)) {
    reply_error(req, -32003, "guard not asserted", guard_name(fx_i2c[idx].guard));
    return;
  }
  fx_out o;
  out_head(&o, req);
  out_lit(&o, ",\"result\":{\"addresses\":[");
  bool first = true;
  uint8_t probe = 0;
  /* 0x00-0x07 and 0x78-0x7f are reserved by the I2C specification. */
  for (uint8_t addr = 0x08; addr < 0x78; addr++) {
    if (fx_hal_i2c_read(fx_i2c[idx].index, addr, &probe, 1) < 0) continue;
    if (!first) out_char(&o, ',');
    first = false;
    out_long(&o, addr);
  }
  out_lit(&o, "]}}");
  out_flush(&o);
}

static bool i2c_address_param(const fx_req* req, fx_str params, bool have_params, long* addr) {
  if (!want_long(req, params, have_params, "address", addr)) return false;
  if (*addr < 0 || *addr > 0x7f) {
    reply_error(req, -32602, "invalid params", "address must be a 7-bit value");
    return false;
  }
  return true;
}

static void method_i2c_write(const fx_req* req, fx_str params, bool have_params) {
  char name[FX_NAME_MAX];
  char hex[FX_PAYLOAD_MAX * 2 + 1];
  long addr = 0;
  if (!want_str(req, params, have_params, "channel", name, sizeof(name))) return;
  int idx = find_i2c(name);
  if (idx < 0) {
    reply_error(req, -32001, "no such i2c channel", name);
    return;
  }
  if (!i2c_address_param(req, params, have_params, &addr)) return;
  if (!want_str(req, params, have_params, "hex", hex, sizeof(hex))) return;
  uint8_t payload[FX_PAYLOAD_MAX];
  long n = hex_decode(hex, payload, sizeof(payload));
  if (n < 0) {
    reply_error(req, -32602, "invalid params", "hex must be an even number of hex digits");
    return;
  }
  if (!guard_satisfied(fx_i2c[idx].guard)) {
    reply_error(req, -32003, "guard not asserted", guard_name(fx_i2c[idx].guard));
    return;
  }
  int rc = fx_hal_i2c_write(fx_i2c[idx].index, (uint8_t)addr, payload, (size_t)n, false);
  if (rc < 0) {
    reply_error(req, -32004, "i2c write failed", name);
    return;
  }
  reply_ok_empty(req);
}

static void method_i2c_read(const fx_req* req, fx_str params, bool have_params) {
  char name[FX_NAME_MAX];
  long addr = 0;
  long length = 0;
  if (!want_str(req, params, have_params, "channel", name, sizeof(name))) return;
  int idx = find_i2c(name);
  if (idx < 0) {
    reply_error(req, -32001, "no such i2c channel", name);
    return;
  }
  if (!i2c_address_param(req, params, have_params, &addr)) return;
  if (!want_long(req, params, have_params, "length", &length)) return;
  if (length <= 0 || length > FX_PAYLOAD_MAX) {
    reply_error(req, -32602, "invalid params", "length out of range");
    return;
  }
  if (!guard_satisfied(fx_i2c[idx].guard)) {
    reply_error(req, -32003, "guard not asserted", guard_name(fx_i2c[idx].guard));
    return;
  }
  uint8_t payload[FX_PAYLOAD_MAX];
  if (fx_hal_i2c_read(fx_i2c[idx].index, (uint8_t)addr, payload, (size_t)length) < 0) {
    reply_error(req, -32004, "i2c read failed", name);
    return;
  }
  fx_out o;
  out_head(&o, req);
  out_lit(&o, ",\"result\":{");
  out_key(&o, "hex");
  out_hex(&o, payload, (size_t)length);
  out_lit(&o, "}}");
  out_flush(&o);
}

static void method_spi_transfer(const fx_req* req, fx_str params, bool have_params) {
  char name[FX_NAME_MAX];
  char hex[FX_PAYLOAD_MAX * 2 + 1];
  if (!want_str(req, params, have_params, "channel", name, sizeof(name))) return;
  int idx = find_spi(name);
  if (idx < 0) {
    reply_error(req, -32001, "no such spi channel", name);
    return;
  }
  if (fx_spi[idx].role != FX_ROLE_MASTER) {
    reply_error(req, -32005, "channel is monitor-only", name);
    return;
  }
  if (!want_str(req, params, have_params, "hex", hex, sizeof(hex))) return;
  uint8_t tx[FX_PAYLOAD_MAX];
  uint8_t rx[FX_PAYLOAD_MAX];
  long n = hex_decode(hex, tx, sizeof(tx));
  if (n < 0) {
    reply_error(req, -32602, "invalid params", "hex must be an even number of hex digits");
    return;
  }
  if (!guard_satisfied(fx_spi[idx].guard)) {
    reply_error(req, -32003, "guard not asserted", guard_name(fx_spi[idx].guard));
    return;
  }
  fx_hal_spi_transfer(fx_spi[idx].index, tx, rx, (size_t)n);
  fx_out o;
  out_head(&o, req);
  out_lit(&o, ",\"result\":{");
  out_key(&o, "hex");
  out_hex(&o, rx, (size_t)n);
  out_lit(&o, "}}");
  out_flush(&o);
}

/* ------------------------------------------------------------------ dispatch */

static void dispatch(const char* line, size_t len) {
  fx_req req = {{NULL, 0}, false};
  const char* end = line + len;

  fx_str id;
  if (obj_get(line, end, "id", &id)) {
    req.id = id;
    req.has_id = true;
  }

  fx_str method_v;
  char method[FX_NAME_MAX * 2];
  if (!obj_get(line, end, "method", &method_v) || !str_value(method_v, method, sizeof(method))) {
    reply_error(&req, -32600, "invalid request", "no method");
    return;
  }

  fx_str params = {NULL, 0};
  bool have_params = obj_get(line, end, "params", &params);

  if (strcmp(method, "fixture.info") == 0) return method_info(&req);
  if (strcmp(method, "fixture.channels") == 0) return method_channels(&req);
  if (strcmp(method, "gpio.read") == 0) return method_gpio_read(&req, params, have_params);
  if (strcmp(method, "gpio.write") == 0) return method_gpio_write(&req, params, have_params);
  if (strcmp(method, "gpio.snapshot") == 0) return method_gpio_snapshot(&req);
  if (strcmp(method, "adc.read") == 0) return method_adc_read(&req, params, have_params);
  if (strcmp(method, "adc.snapshot") == 0) return method_adc_snapshot(&req);
  if (strcmp(method, "uart.write") == 0) return method_uart_write(&req, params, have_params);
  if (strcmp(method, "uart.read") == 0) return method_uart_read(&req, params, have_params);
  if (strcmp(method, "uart.configure") == 0)
    return method_uart_configure(&req, params, have_params);
  if (strcmp(method, "i2c.scan") == 0) return method_i2c_scan(&req, params, have_params);
  if (strcmp(method, "i2c.write") == 0) return method_i2c_write(&req, params, have_params);
  if (strcmp(method, "i2c.read") == 0) return method_i2c_read(&req, params, have_params);
  if (strcmp(method, "spi.transfer") == 0) return method_spi_transfer(&req, params, have_params);

  reply_error(&req, -32601, "method not found", method);
}

/* ------------------------------------------------------------------ line assembly */

static char g_line[FX_LINE_MAX];
static size_t g_line_len;
static bool g_line_too_long;

void fx_core_feed_byte(char c) {
  if (c == '\r') return;
  if (c != '\n') {
    if (g_line_len < sizeof(g_line))
      g_line[g_line_len++] = c;
    else
      g_line_too_long = true;
    return;
  }

  if (g_line_too_long) {
    fx_req none = {{NULL, 0}, false};
    reply_error(&none, -32600, "invalid request", "line longer than FX_LINE_MAX");
  } else if (g_line_len > 0) {
    dispatch(g_line, g_line_len);
  }
  g_line_len = 0;
  g_line_too_long = false;
}

void fx_core_feed(const char* data, size_t len) {
  for (size_t i = 0; i < len; i++) fx_core_feed_byte(data[i]);
}

/* ------------------------------------------------------------------ startup and streaming */

void fx_core_init(void) {
  g_line_len = 0;
  g_line_too_long = false;

  for (size_t i = 0; i < fx_gpio_count; i++) {
    const fx_gpio_desc* g = &fx_gpio[i];
    fx_hal_gpio_configure(g->pin, g->direction, g->pull);
    if (g->direction != FX_DIR_INPUT) gpio_drive(g, g->initial_asserted);
  }
  for (size_t i = 0; i < fx_uart_count; i++) {
    const fx_uart_desc* u = &fx_uart[i];
    fx_hal_uart_configure(u->index, u->baud, u->data_bits, u->stop_bits, u->parity);
  }
  for (size_t i = 0; i < fx_spi_count; i++) {
    const fx_spi_desc* s = &fx_spi[i];
    if (s->role == FX_ROLE_MASTER) fx_hal_spi_configure(s->index, s->hz, s->mode);
  }

  fx_out o;
  notify_begin(&o, "fixture.ready");
  out_kv_str(&o, "fixture", fx_fixture_name);
  out_char(&o, ',');
  out_kv_str(&o, "version", fx_fixture_version);
  out_char(&o, ',');
  out_kv_str(&o, "config_hash", fx_config_hash);
  notify_end(&o);
}

void fx_core_poll(void) {
  /* Anything arriving on a streamed UART is pushed to the agent unasked, so a log line shows up
   * as soon as the DUT emits it rather than whenever someone remembers to poll. */
  for (size_t i = 0; i < fx_uart_count; i++) {
    const fx_uart_desc* u = &fx_uart[i];
    if (!u->stream) continue;
    uint8_t payload[FX_PAYLOAD_MAX];
    size_t n = fx_hal_uart_read(u->index, payload, sizeof(payload));
    if (n == 0) continue;
    fx_out o;
    notify_begin(&o, "uart.data");
    out_kv_str(&o, "channel", u->name);
    out_char(&o, ',');
    out_key(&o, "hex");
    out_hex(&o, payload, n);
    out_char(&o, ',');
    out_kv_long(&o, "length", (long)n);
    out_char(&o, ',');
    out_kv_long(&o, "t_ms", (long)fx_hal_millis());
    notify_end(&o);
  }
}
