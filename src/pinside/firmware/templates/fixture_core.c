/* JSON-RPC 2.0 over the USB CDC line: one request per line, one response per line.
 *
 * The DUT-facing behaviour is all table-driven from fixture_config.c, so this file is the same
 * for every fixture pinside generates. It holds no SDK headers, which is what lets test/run.sh
 * build it on a host against a mock HAL.
 *
 * Two deliberate simplifications, both safe for the traffic this protocol carries:
 *   * The JSON reader only looks up keys at the top level of an object. It skips nested values
 *     correctly, so "params" is reachable, but there is no general document model.
 *   * Payloads travel as hex strings. Base64 would be denser; hex is trivial to verify by eye
 *     in a log, and an agent reading a capture cares more about that than about bytes on the wire.
 *
 * Generated by pinside. Regenerating overwrites this file.
 */

#include "fixture_core.h"

#include <string.h>

#include "fixture_config.h"
#include "fixture_hal.h"

/* ------------------------------------------------------------------ JSON reading */

typedef struct {
  const char* p;
  size_t n;
} fx_str;

static const char* skip_ws(const char* p, const char* end) {
  while (p < end && (*p == ' ' || *p == '\t' || *p == '\n' || *p == '\r')) p++;
  return p;
}

static const char* skip_string(const char* p, const char* end) {
  if (p >= end || *p != '"') return NULL;
  p++;
  while (p < end) {
    if (*p == '\\') {
      p += 2;
      continue;
    }
    if (*p == '"') return p + 1;
    p++;
  }
  return NULL;
}

/* Advance past one complete JSON value, whatever its depth. */
static const char* skip_value(const char* p, const char* end) {
  p = skip_ws(p, end);
  if (p >= end) return NULL;
  if (*p == '"') return skip_string(p, end);
  if (*p == '{' || *p == '[') {
    char open = *p;
    char close = (open == '{') ? '}' : ']';
    int depth = 0;
    while (p < end) {
      if (*p == '"') {
        p = skip_string(p, end);
        if (!p) return NULL;
        continue;
      }
      if (*p == open) depth++;
      if (*p == close) {
        depth--;
        if (depth == 0) return p + 1;
      }
      p++;
    }
    return NULL;
  }
  while (p < end && *p != ',' && *p != '}' && *p != ']' && *p != ' ' && *p != '\t' && *p != '\n' &&
         *p != '\r')
    p++;
  return p;
}

/* Find key at the top level of the object starting at p. */
static bool obj_get(const char* p, const char* end, const char* key, fx_str* out) {
  p = skip_ws(p, end);
  if (p >= end || *p != '{') return false;
  p++;
  size_t keylen = strlen(key);
  for (;;) {
    p = skip_ws(p, end);
    if (p >= end || *p == '}') return false;
    const char* name = p + 1;
    const char* after = skip_string(p, end);
    if (!after) return false;
    size_t namelen = (size_t)(after - name - 1);
    p = skip_ws(after, end);
    if (p >= end || *p != ':') return false;
    p = skip_ws(p + 1, end);
    const char* value = p;
    const char* value_end = skip_value(p, end);
    if (!value_end) return false;
    if (namelen == keylen && memcmp(name, key, keylen) == 0) {
      out->p = value;
      out->n = (size_t)(value_end - value);
      return true;
    }
    p = skip_ws(value_end, end);
    if (p < end && *p == ',') {
      p++;
      continue;
    }
    return false;
  }
}

static bool str_value(fx_str v, char* buf, size_t cap) {
  if (v.n < 2 || v.p[0] != '"') return false;
  const char* p = v.p + 1;
  const char* end = v.p + v.n - 1;
  size_t o = 0;
  while (p < end && o + 1 < cap) {
    char c = *p++;
    if (c == '\\' && p < end) {
      char e = *p++;
      switch (e) {
        case 'n': c = '\n'; break;
        case 't': c = '\t'; break;
        case 'r': c = '\r'; break;
        case 'b': c = '\b'; break;
        case 'f': c = '\f'; break;
        case 'u': /* no UTF-16 in a channel name; keep the placeholder visible */
          if (end - p >= 4) p += 4;
          c = '?';
          break;
        default: c = e; break;
      }
    }
    buf[o++] = c;
  }
  buf[o] = '\0';
  return p >= end;
}

static bool int_value(fx_str v, long* out) {
  const char* p = v.p;
  const char* end = v.p + v.n;
  bool neg = false;
  if (p < end && (*p == '-' || *p == '+')) neg = (*p++ == '-');
  if (p >= end) return false;
  long acc = 0;
  bool any = false;
  while (p < end && *p >= '0' && *p <= '9') {
    acc = acc * 10 + (*p++ - '0');
    any = true;
  }
  if (!any) return false;
  *out = neg ? -acc : acc;
  return true;
}

static bool bool_value(fx_str v, bool* out) {
  if (v.n == 4 && memcmp(v.p, "true", 4) == 0) {
    *out = true;
    return true;
  }
  if (v.n == 5 && memcmp(v.p, "false", 5) == 0) {
    *out = false;
    return true;
  }
  return false;
}

/* ------------------------------------------------------------------ JSON writing */

/* A response is streamed, not assembled. fixture.channels on a real fixture runs to several
 * kilobytes -- more than a fixture wants to hold -- and buffering it whole was the first thing
 * the host tests caught. Chunking has one consequence worth knowing: once the first chunk has
 * gone out a response cannot be retracted, so every failure must be decided before writing. */
typedef struct {
  char buf[FX_OUT_CHUNK];
  size_t len;
} fx_out;

static void out_drain(fx_out* o) {
  if (o->len == 0) return;
  fx_hal_write(o->buf, o->len);
  o->len = 0;
}

static void out_raw(fx_out* o, const char* s, size_t n) {
  while (n > 0) {
    size_t room = sizeof(o->buf) - o->len;
    if (room == 0) {
      out_drain(o);
      room = sizeof(o->buf);
    }
    size_t take = n < room ? n : room;
    memcpy(o->buf + o->len, s, take);
    o->len += take;
    s += take;
    n -= take;
  }
}

static void out_lit(fx_out* o, const char* s) { out_raw(o, s, strlen(s)); }

static void out_char(fx_out* o, char c) { out_raw(o, &c, 1); }

static void out_escaped(fx_out* o, const char* s) {
  out_char(o, '"');
  for (; *s; s++) {
    switch (*s) {
      case '"': out_lit(o, "\\\""); break;
      case '\\': out_lit(o, "\\\\"); break;
      case '\n': out_lit(o, "\\n"); break;
      case '\r': out_lit(o, "\\r"); break;
      case '\t': out_lit(o, "\\t"); break;
      default:
        if ((unsigned char)*s < 0x20) {
          static const char hex[] = "0123456789abcdef";
          char esc[6] = {'\\', 'u', '0', '0', 0, 0};
          esc[4] = hex[((unsigned char)*s >> 4) & 0xf];
          esc[5] = hex[(unsigned char)*s & 0xf];
          out_raw(o, esc, 6);
        } else {
          out_char(o, *s);
        }
    }
  }
  out_char(o, '"');
}

static void out_long(fx_out* o, long v) {
  char tmp[24];
  size_t i = sizeof(tmp);
  unsigned long mag = (v < 0) ? (unsigned long)(-(v + 1)) + 1UL : (unsigned long)v;
  do {
    tmp[--i] = (char)('0' + (mag % 10));
    mag /= 10;
  } while (mag && i);
  if (v < 0 && i) tmp[--i] = '-';
  out_raw(o, tmp + i, sizeof(tmp) - i);
}

static void out_key(fx_out* o, const char* key) {
  out_escaped(o, key);
  out_char(o, ':');
}

static void out_kv_str(fx_out* o, const char* key, const char* value) {
  out_key(o, key);
  out_escaped(o, value);
}

static void out_kv_long(fx_out* o, const char* key, long value) {
  out_key(o, key);
  out_long(o, value);
}

static void out_kv_bool(fx_out* o, const char* key, bool value) {
  out_key(o, key);
  out_lit(o, value ? "true" : "false");
}

static void out_flush(fx_out* o) {
  out_char(o, '\n');
  out_drain(o);
}

/* ------------------------------------------------------------------ hex payloads */

static int hex_digit(char c) {
  if (c >= '0' && c <= '9') return c - '0';
  if (c >= 'a' && c <= 'f') return c - 'a' + 10;
  if (c >= 'A' && c <= 'F') return c - 'A' + 10;
  return -1;
}

static long hex_decode(const char* s, uint8_t* out, size_t cap) {
  size_t n = 0;
  while (*s) {
    int hi = hex_digit(*s++);
    if (hi < 0 || !*s) return -1;
    int lo = hex_digit(*s++);
    if (lo < 0) return -1;
    if (n >= cap) return -1;
    out[n++] = (uint8_t)((hi << 4) | lo);
  }
  return (long)n;
}

static void out_hex(fx_out* o, const uint8_t* data, size_t len) {
  static const char hex[] = "0123456789abcdef";
  out_char(o, '"');
  for (size_t i = 0; i < len; i++) {
    out_char(o, hex[data[i] >> 4]);
    out_char(o, hex[data[i] & 0xf]);
  }
  out_char(o, '"');
}

