/* ------------------------------------------------------------------ gpio semantics */

static bool gpio_is_asserted(const fx_gpio_desc* g) {
  bool level = fx_hal_gpio_get(g->pin);
  return g->active_low ? !level : level;
}

static void gpio_drive(const fx_gpio_desc* g, bool assert_it) {
  if (g->direction == FX_DIR_OPEN_DRAIN) {
    /* Only ever pull towards the asserted rail; releasing means going high-Z, which is what
     * keeps the fixture from fighting the DUT's own pull-up on a line like ESP_EN. */
    if (assert_it)
      fx_hal_gpio_set(g->pin, g->active_low ? false : true);
    else
      fx_hal_gpio_release(g->pin);
    return;
  }
  fx_hal_gpio_set(g->pin, g->active_low ? !assert_it : assert_it);
}

/* A bus whose lines the DUT also drives may only be mastered while its guard is asserted. */
static bool guard_satisfied(int8_t guard) {
  if (guard < 0) return true;
  return gpio_is_asserted(&fx_gpio[guard]);
}

static const char* guard_name(int8_t guard) { return guard < 0 ? "" : fx_gpio[guard].name; }

/* ------------------------------------------------------------------ responses */

typedef struct {
  fx_str id;
  bool has_id;
} fx_req;

static void out_head(fx_out* o, const fx_req* req) {
  o->len = 0;
  out_lit(o, "{\"jsonrpc\":\"2.0\",\"id\":");
  if (req->has_id)
    out_raw(o, req->id.p, req->id.n);
  else
    out_lit(o, "null");
}

static void reply_error(const fx_req* req, long code, const char* message, const char* data) {
  fx_out o;
  out_head(&o, req);
  out_lit(&o, ",\"error\":{");
  out_kv_long(&o, "code", code);
  out_char(&o, ',');
  out_kv_str(&o, "message", message);
  if (data && *data) {
    out_char(&o, ',');
    out_kv_str(&o, "data", data);
  }
  out_lit(&o, "}}");
  out_flush(&o);
}

static void reply_ok_empty(const fx_req* req) {
  fx_out o;
  out_head(&o, req);
  out_lit(&o, ",\"result\":{}}");
  out_flush(&o);
}

static void notify_begin(fx_out* o, const char* method) {
  o->len = 0;
  out_lit(o, "{\"jsonrpc\":\"2.0\",\"method\":");
  out_escaped(o, method);
  out_lit(o, ",\"params\":{");
}

static void notify_end(fx_out* o) {
  out_lit(o, "}}");
  out_flush(o);
}

/* ------------------------------------------------------------------ methods */

static void emit_gpio_state(fx_out* o, const fx_gpio_desc* g) {
  out_lit(o, "{");
  out_kv_str(o, "channel", g->name);
  out_char(o, ',');
  out_kv_str(o, "probe", g->probe);
  out_char(o, ',');
  out_kv_long(o, "pin", g->pin);
  out_char(o, ',');
  out_kv_bool(o, "level", fx_hal_gpio_get(g->pin));
  out_char(o, ',');
  out_kv_bool(o, "asserted", gpio_is_asserted(g));
  out_lit(o, "}");
}

static void emit_adc_state(fx_out* o, const fx_adc_desc* a) {
  uint16_t raw = fx_hal_adc_read(a->adc);
  uint32_t full = fx_hal_adc_full_scale();
  uint32_t at_pin_mv = full ? (uint32_t)raw * fx_hal_adc_reference_mv() / full : 0;
  /* divider_milli is the ratio the external network divides by, times 1000. */
  long mv = (long)((uint64_t)at_pin_mv * a->divider_milli / 1000u);

  out_lit(o, "{");
  out_kv_str(o, "channel", a->name);
  out_char(o, ',');
  out_kv_str(o, "probe", a->probe);
  out_char(o, ',');
  out_kv_long(o, "millivolts", mv);
  out_char(o, ',');
  out_kv_long(o, "raw", raw);
  if (a->nominal_mv >= 0) {
    long low = a->nominal_mv - a->tolerance_mv;
    long high = a->nominal_mv + a->tolerance_mv;
    out_char(o, ',');
    out_kv_long(o, "nominal_mv", a->nominal_mv);
    out_char(o, ',');
    out_kv_bool(o, "in_range", mv >= low && mv <= high);
  }
  out_lit(o, "}");
}

static void method_info(const fx_req* req) {
  fx_out o;
  out_head(&o, req);
  out_lit(&o, ",\"result\":{");
  out_kv_str(&o, "fixture", fx_fixture_name);
  out_char(&o, ',');
  out_kv_str(&o, "version", fx_fixture_version);
  out_char(&o, ',');
  out_kv_str(&o, "mcu", fx_target_mcu);
  out_char(&o, ',');
  out_kv_str(&o, "dut_board", fx_dut_board);
  out_char(&o, ',');
  out_kv_str(&o, "config_hash", fx_config_hash);
  out_char(&o, ',');
  out_kv_long(&o, "uptime_ms", (long)fx_hal_millis());
  out_char(&o, ',');
  out_key(&o, "counts");
  out_lit(&o, "{");
  out_kv_long(&o, "gpio", (long)fx_gpio_count);
  out_char(&o, ',');
  out_kv_long(&o, "adc", (long)fx_adc_count);
  out_char(&o, ',');
  out_kv_long(&o, "uart", (long)fx_uart_count);
  out_char(&o, ',');
  out_kv_long(&o, "i2c", (long)fx_i2c_count);
  out_char(&o, ',');
  out_kv_long(&o, "spi", (long)fx_spi_count);
  out_lit(&o, "}}}");
  out_flush(&o);
}

static void emit_bus_entry(fx_out* o, const char* kind, const char* name, const char* probe_list,
                           int8_t guard, bool stream) {
  out_lit(o, "{");
  out_kv_str(o, "channel", name);
  out_char(o, ',');
  out_kv_str(o, "kind", kind);
  out_char(o, ',');
  out_kv_str(o, "probes", probe_list);
  out_char(o, ',');
  out_kv_str(o, "guard", guard_name(guard));
  out_char(o, ',');
  out_kv_bool(o, "stream", stream);
  out_lit(o, "}");
}

static void method_channels(const fx_req* req) {
  fx_out o;
  out_head(&o, req);
  out_lit(&o, ",\"result\":[");
  bool first = true;
  for (size_t i = 0; i < fx_gpio_count; i++) {
    if (!first) out_char(&o, ',');
    first = false;
    out_lit(&o, "{");
    out_kv_str(&o, "channel", fx_gpio[i].name);
    out_char(&o, ',');
    out_kv_str(&o, "kind", "gpio");
    out_char(&o, ',');
    out_kv_str(&o, "probe", fx_gpio[i].probe);
    out_char(&o, ',');
    out_kv_long(&o, "pin", fx_gpio[i].pin);
    out_char(&o, ',');
    out_kv_bool(&o, "writable", fx_gpio[i].direction != FX_DIR_INPUT);
    out_char(&o, ',');
    out_kv_str(&o, "description", fx_gpio[i].description);
    out_lit(&o, "}");
  }
  for (size_t i = 0; i < fx_adc_count; i++) {
    if (!first) out_char(&o, ',');
    first = false;
    out_lit(&o, "{");
    out_kv_str(&o, "channel", fx_adc[i].name);
    out_char(&o, ',');
    out_kv_str(&o, "kind", "adc");
    out_char(&o, ',');
    out_kv_str(&o, "probe", fx_adc[i].probe);
    out_char(&o, ',');
    out_kv_long(&o, "pin", fx_adc[i].pin);
    out_char(&o, ',');
    out_kv_str(&o, "description", fx_adc[i].description);
    out_lit(&o, "}");
  }
  for (size_t i = 0; i < fx_uart_count; i++) {
    if (!first) out_char(&o, ',');
    first = false;
    emit_bus_entry(&o, "uart", fx_uart[i].name, fx_uart[i].probe_summary, fx_uart[i].guard,
                   fx_uart[i].stream);
  }
  for (size_t i = 0; i < fx_i2c_count; i++) {
    if (!first) out_char(&o, ',');
    first = false;
    emit_bus_entry(&o, "i2c", fx_i2c[i].name, fx_i2c[i].probe_summary, fx_i2c[i].guard, false);
  }
  for (size_t i = 0; i < fx_spi_count; i++) {
    if (!first) out_char(&o, ',');
    first = false;
    emit_bus_entry(&o, "spi", fx_spi[i].name, fx_spi[i].probe_summary, fx_spi[i].guard, false);
  }
  out_lit(&o, "]}");
  out_flush(&o);
}

/* Pull a required string parameter. Replies with an error and returns false if absent. */
static bool want_str(const fx_req* req, fx_str params, bool have_params, const char* key, char* buf,
                     size_t cap) {
  fx_str v;
  if (!have_params || !obj_get(params.p, params.p + params.n, key, &v) || !str_value(v, buf, cap)) {
    reply_error(req, -32602, "invalid params", key);
    return false;
  }
  return true;
}

static bool want_long(const fx_req* req, fx_str params, bool have_params, const char* key,
                      long* out) {
  fx_str v;
  if (!have_params || !obj_get(params.p, params.p + params.n, key, &v) || !int_value(v, out)) {
    reply_error(req, -32602, "invalid params", key);
    return false;
  }
  return true;
}

static void method_gpio_read(const fx_req* req, fx_str params, bool have_params) {
  char name[FX_NAME_MAX];
  if (!want_str(req, params, have_params, "channel", name, sizeof(name))) return;
  int idx = find_gpio(name);
  if (idx < 0) {
    reply_error(req, -32001, "no such gpio channel", name);
    return;
  }
  fx_out o;
  out_head(&o, req);
  out_lit(&o, ",\"result\":");
  emit_gpio_state(&o, &fx_gpio[idx]);
  out_lit(&o, "}");
  out_flush(&o);
}

static void method_gpio_write(const fx_req* req, fx_str params, bool have_params) {
  char name[FX_NAME_MAX];
  if (!want_str(req, params, have_params, "channel", name, sizeof(name))) return;
  int idx = find_gpio(name);
  if (idx < 0) {
    reply_error(req, -32001, "no such gpio channel", name);
    return;
  }
  const fx_gpio_desc* g = &fx_gpio[idx];
  if (g->direction == FX_DIR_INPUT) {
    reply_error(req, -32002, "channel is an input", name);
    return;
  }
  fx_str v;
  bool assert_it = false;
  if (!have_params || !obj_get(params.p, params.p + params.n, "assert", &v) ||
      !bool_value(v, &assert_it)) {
    reply_error(req, -32602, "invalid params", "assert");
    return;
  }
  gpio_drive(g, assert_it);
  fx_out o;
  out_head(&o, req);
  out_lit(&o, ",\"result\":");
  emit_gpio_state(&o, g);
  out_lit(&o, "}");
  out_flush(&o);
}

